//! The app's own words, in the kit's two UI languages; the status wording matches `todo/locales`.
#[derive(Clone, Copy, PartialEq)]
pub enum Lang { En, Ko }

impl Lang {
    pub fn parse(value: &str) -> Lang { if value.starts_with("ko") { Lang::Ko } else { Lang::En } }
}

